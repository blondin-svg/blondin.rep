def apply_patch(target):
    target = Path(target)
    if not target.exists():
        print(f"ERREUR: fichier introuvable: {target}")
        return 2

    original = target.read_text(encoding="utf-8")

    if MARKER in original and "ROM_SOURCES" in original:
        print("Patch multi-sources déjà présent.")
        if not apply_companion_hub_patch():
            print("AVERTISSEMENT : multi-sources OK, mais correction du hub Mini PC impossible.")
        return 0

    work = original
    line_offset = 0

    for hunk in HUNKS:
        work, delta = _apply_one_hunk(work, hunk, line_offset)
        if work is None:
            print("Aucun fichier n'a été modifié.")
            return 20
        line_offset += delta

    if MARKER not in work or "ROM_SOURCES" not in work:
        print("ERREUR: validation fonctionnelle du patch impossible.")
        return 90

    # Valider d'abord sur un fichier temporaire : la version officielle reste
    # intacte tant que la totalité du patch n'est pas jugée valide.
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".py", delete=False) as tmp:
        tmp.write(work)
        tmp_path = Path(tmp.name)

    try:
        py_compile.compile(str(tmp_path), doraise=True)
    except Exception as e:
        print(f"ERREUR: le fichier patché ne compile pas: {e}")
        try:
            tmp_path.unlink()
        except Exception:
            pass
        return 91

    backup = target.with_name(
        target.name + f".official-before-multisource-{int(time.time())}.bak"
    )

    try:
        shutil.copy2(target, backup)
        target.write_text(work, encoding="utf-8")
        py_compile.compile(str(target), doraise=True)
    except Exception as e:
        try:
            if backup.exists():
                shutil.copy2(backup, target)
        except Exception:
            pass
        print(f"ERREUR: installation finale impossible: {e}")
        return 92
    finally:
        try:
            tmp_path.unlink()
        except Exception:
            pass

    print(f"OK: patch multi-sources appliqué ({len(HUNKS)} étapes).")
    print(f"Sauvegarde de la version officielle: {backup}")
    print(f"SHA256 avant: {sha256_text(original)}")
    print(f"SHA256 après: {sha256_text(work)}")
    if not apply_companion_hub_patch():
        print("AVERTISSEMENT : multi-sources installé, mais correction du hub Mini PC impossible.")
    return 0


