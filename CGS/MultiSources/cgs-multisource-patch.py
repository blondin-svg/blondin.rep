def sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _line_of(text, char_pos):
    return text.count("\n", 0, char_pos) + 1


def _find_all(text, needle):
    out = []
    start = 0
    while True:
        pos = text.find(needle, start)
        if pos < 0:
            break
        out.append(pos)
        start = pos + 1
    return out


def _candidate_blocks(old_lines, new_lines, common_pre, common_post):
    # On essaie d'abord tout le hunk (plus sûr), puis on réduit uniquement
    # le contexte inchangé. Les lignes réellement modifiées ne sont jamais
    # supprimées des critères de recherche.
    max_ctx = max(common_pre, common_post, 3)
    seen = set()
    for keep in range(max_ctx, -1, -1):
        kp = min(common_pre, keep)
        ks = min(common_post, keep)
        old_start = common_pre - kp
        old_end = len(old_lines) - (common_post - ks)
        new_start = common_pre - kp
        new_end = len(new_lines) - (common_post - ks)
        old_block = "".join(old_lines[old_start:old_end])
        new_block = "".join(new_lines[new_start:new_end])
        if not old_block:
            continue
        key = (old_block, new_block)
        if key in seen:
            continue
        seen.add(key)
        yield keep, old_block, new_block


def _apply_one_hunk(work, hunk, line_offset):
    idx, header, base_start, old_lines, new_lines, common_pre, common_post = hunk
    expected_line = max(1, base_start + line_offset)

    for keep, old_block, new_block in _candidate_blocks(
        old_lines, new_lines, common_pre, common_post
    ):
        positions = _find_all(work, old_block)
        if not positions:
            continue

        ranked = sorted(
            ((abs(_line_of(work, p) - expected_line), p, _line_of(work, p)) for p in positions),
            key=lambda x: (x[0], x[2]),
        )

        # Si plusieurs occurrences sont possibles, la position attendue issue
        # du diff permet de sélectionner le bon bloc. Par prudence, si les deux
        # meilleurs candidats sont exactement à la même distance, on refuse.
        if len(ranked) > 1 and ranked[0][0] == ranked[1][0]:
            continue

        _, pos, actual_line = ranked[0]
        work = work[:pos] + new_block + work[pos + len(old_block):]
        delta = len(new_lines) - len(old_lines)
        print(
            f"Etape {idx:02d}: OK (ligne ~{actual_line}, contexte={keep}, delta={delta:+d})"
        )
        return work, delta

    print(f"INCOMPATIBLE: étape {idx} {header}")
    print(f"Bloc attendu introuvable près de la ligne {expected_line}.")
    return None, 0


